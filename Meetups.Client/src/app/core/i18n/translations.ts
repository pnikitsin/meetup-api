const dictionaries: Record<Language, Record<string, string>> = {
  ru,
  en,
};

const pluralRules = new Map<string, Intl.PluralRules>();

function rulesFor(language: Language): Intl.PluralRules {
  const locale = localeFor(language);
  let rules = pluralRules.get(locale);

  if (!rules) {
    rules = new Intl.PluralRules(locale);
    pluralRules.set(locale, rules);
  }

  return rules;
}

function interpolate(template: string, params: TranslationParams): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

export function translate(
  language: Language,
  key: TranslationKey,
  params: TranslationParams = {},
): string {
  const template = dictionaries[language][key] ?? dictionaries.ru[key] ?? key;
  return interpolate(template, params);
}

/**
 * Выбирает форму по правилам Intl.PluralRules и подставляет count.
 * Для русского доступны one/few/many/other, для английского — one/other.
 */
export function pluralTranslate(
  language: Language,
  key: string,
  count: number,
  params: TranslationParams = {},
): string {
  const category = rulesFor(language).select(count);
  const dictionary = dictionaries[language];
  const candidates = [`${key}.${category}`, `${key}.other`, `${key}.many`, key];
  const template = candidates.map((candidate) => dictionary[candidate]).find(Boolean);

  return interpolate(template ?? key, { count, ...params });
}

export function formatCount(
  language: Language,
  count: number,
  unit: 'day' | 'hour' | 'minute' | 'minuteAccusative',
): string {
  return `${count} ${pluralTranslate(language, `time.unit.${unit}`, count)}`;
}
